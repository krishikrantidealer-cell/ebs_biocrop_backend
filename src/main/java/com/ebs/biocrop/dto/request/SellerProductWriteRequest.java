package com.ebs.biocrop.dto.request;

import com.ebs.biocrop.entity.Product;
import com.ebs.biocrop.entity.ProductVariant;
import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import com.ebs.biocrop.entity.enums.PaymentMethod;
import jakarta.validation.constraints.Size;

import java.util.List;

/** Seller-controlled product content; server-owned identity, moderation, and metrics are excluded. */
public class SellerProductWriteRequest {
    /** Optional legacy request property; SKU values are now generated by the server. */
    @JsonIgnore @Size(max = 80) private String sku;
    @Size(max = 32) private String hsnCode;
    @NotBlank @Size(max = 200) private String title;
    @Size(max = 300) private String technicalName;
    @Size(max = 100000) private String description;
    @NotBlank private String categoryId;
    @Size(max = 2000) private String refundPolicy;
    @PositiveOrZero private Double productWeight;
    @Size(max = 10) private String productWeightUnit;
    @NotEmpty @Size(max = 50) @Valid private List<VariantWriteRequest> variants;

    public Product toProduct() {
        Product product = new Product();
        product.setHsnCode(hsnCode);
        product.setTitle(title); product.setTechnicalName(technicalName);
        product.setDescription(description); product.setCategoryId(categoryId);
        product.setRefundPolicy(refundPolicy); product.setProductWeight(productWeight); product.setProductWeightUnit(productWeightUnit);
        product.setVariants(variants == null ? List.of() : variants.stream().map(VariantWriteRequest::toVariant).toList());
        return product;
    }

    public String getSku() { return sku; }
    public void setSku(String sku) { this.sku = sku; }
    public String getHsnCode() { return hsnCode; }
    public void setHsnCode(String hsnCode) { this.hsnCode = hsnCode; }
    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }
    public String getTechnicalName() { return technicalName; }
    public void setTechnicalName(String technicalName) { this.technicalName = technicalName; }
    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }
    public String getCategoryId() { return categoryId; }
    public void setCategoryId(String categoryId) { this.categoryId = categoryId; }
    public String getRefundPolicy() { return refundPolicy; }
    public void setRefundPolicy(String refundPolicy) { this.refundPolicy = refundPolicy; }
    public Double getProductWeight() { return productWeight; }
    public void setProductWeight(Double productWeight) { this.productWeight = productWeight; }
    public String getProductWeightUnit() { return productWeightUnit; }
    public void setProductWeightUnit(String productWeightUnit) { this.productWeightUnit = productWeightUnit; }
    public List<VariantWriteRequest> getVariants() { return variants; }
    public void setVariants(List<VariantWriteRequest> variants) { this.variants = variants; }

    public static class VariantWriteRequest {
        @Size(max = 24) private String id;
        @Size(max = 160) private String label;
        @NotBlank @Size(max = 20) private String unit;
        @NotNull @Positive private Integer packSize;
        @NotBlank @Size(max = 20) private String packSizeUnit;
        @NotNull @Positive private Integer packQuantity;
        @Size(max = 120) private String shippedBy;
        @PositiveOrZero private Double swg;
        @Size(max = 10) @Valid private List<com.ebs.biocrop.entity.ProductDimensions> dimensions;
        @NotNull @PositiveOrZero private Double displayRate;
        @PositiveOrZero private Double printedMrp;
        @PositiveOrZero private Double costPrice;
        @PositiveOrZero private Double amountYouWillReceive;
        @PositiveOrZero @DecimalMax("100") private Double commissionPercentage;
        @PositiveOrZero private Double courierCharges;
        @PositiveOrZero @DecimalMax("100") private Double gstPercentage;
        @PositiveOrZero private Double discountOnMrpRs;
        @PositiveOrZero @DecimalMax("100") private Double discountPercentage;
        @NotNull @PositiveOrZero private Integer stock;
        private PaymentMethod paymentMethod = PaymentMethod.ONLINE;
        private Boolean isPrepaidAllowed = true;
        private Boolean isPartialPaymentAllowed = true;
        @DecimalMin("10") @DecimalMax("99") private Double minimumPartialPaymentPercentage = 10.0;
        @PositiveOrZero private Double codCharge = 30.0;
        /** Optional legacy request property; SKU values are now generated by the server. */
        @JsonIgnore @Size(max = 80) private String sku;

        public ProductVariant toVariant() {
            ProductVariant variant = new ProductVariant();
            variant.setId(id);
            variant.setLabel(label); variant.setUnit(unit); variant.setPackSize(packSize);
            variant.setPackSizeUnit(packSizeUnit); variant.setPackQuantity(packQuantity);
            variant.setShippedBy(shippedBy); variant.setSwg(swg); variant.setDimensions(dimensions);
            variant.setDisplayRate(displayRate); variant.setPrintedMrp(printedMrp); variant.setCostPrice(costPrice);
            variant.setAmountYouWillReceive(amountYouWillReceive);
            variant.setCommissionPercentage(commissionPercentage); variant.setCourierCharges(courierCharges);
            variant.setGstPercentage(gstPercentage); variant.setDiscountOnMrpRs(discountOnMrpRs);
            variant.setDiscountPercentage(discountPercentage); variant.setStock(stock); variant.setPaymentMethod(paymentMethod);
            variant.setIsPrepaidAllowed(isPrepaidAllowed); variant.setIsPartialPaymentAllowed(isPartialPaymentAllowed);
            variant.setMinimumPartialPaymentPercentage(minimumPartialPaymentPercentage);
            variant.setCodCharge(codCharge);
            return variant;
        }

        public String getLabel() { return label; }
        public void setLabel(String label) { this.label = label; }
        public String getId() { return id; }
        public void setId(String id) { this.id = id; }
        public String getUnit() { return unit; }
        public void setUnit(String unit) { this.unit = unit; }
        public Integer getPackSize() { return packSize; }
        public void setPackSize(Integer packSize) { this.packSize = packSize; }
        public String getPackSizeUnit() { return packSizeUnit; }
        public void setPackSizeUnit(String packSizeUnit) { this.packSizeUnit = packSizeUnit; }
        public Integer getPackQuantity() { return packQuantity; }
        public void setPackQuantity(Integer packQuantity) { this.packQuantity = packQuantity; }
        public String getShippedBy() { return shippedBy; }
        public void setShippedBy(String shippedBy) { this.shippedBy = shippedBy; }
        public Double getSwg() { return swg; }
        public void setSwg(Double swg) { this.swg = swg; }
        public List<com.ebs.biocrop.entity.ProductDimensions> getDimensions() { return dimensions; }
        public void setDimensions(List<com.ebs.biocrop.entity.ProductDimensions> dimensions) { this.dimensions = dimensions; }
        public Double getAmountYouWillReceive() { return amountYouWillReceive; }
        public void setAmountYouWillReceive(Double amountYouWillReceive) { this.amountYouWillReceive = amountYouWillReceive; }
        public Double getDisplayRate() { return displayRate; }
        public void setDisplayRate(Double displayRate) { this.displayRate = displayRate; }
        public Double getDiscountOnMrpRs() { return discountOnMrpRs; }
        public void setDiscountOnMrpRs(Double discountOnMrpRs) { this.discountOnMrpRs = discountOnMrpRs; }
        public Double getDiscountPercentage() { return discountPercentage; }
        public void setDiscountPercentage(Double discountPercentage) { this.discountPercentage = discountPercentage; }
        public Double getPrintedMrp() { return printedMrp; }
        public void setPrintedMrp(Double printedMrp) { this.printedMrp = printedMrp; }
        public Double getCostPrice() { return costPrice; }
        public void setCostPrice(Double costPrice) { this.costPrice = costPrice; }
        public Double getCommissionPercentage() { return commissionPercentage; }
        public void setCommissionPercentage(Double commissionPercentage) { this.commissionPercentage = commissionPercentage; }
        public Double getCourierCharges() { return courierCharges; }
        public void setCourierCharges(Double courierCharges) { this.courierCharges = courierCharges; }
        public Double getGstPercentage() { return gstPercentage; }
        public void setGstPercentage(Double gstPercentage) { this.gstPercentage = gstPercentage; }
        public PaymentMethod getPaymentMethod() { return paymentMethod; }
        public void setPaymentMethod(PaymentMethod paymentMethod) { this.paymentMethod = paymentMethod; }
        public Boolean getIsPrepaidAllowed() { return isPrepaidAllowed; }
        public void setIsPrepaidAllowed(Boolean isPrepaidAllowed) { this.isPrepaidAllowed = isPrepaidAllowed; }
        public Boolean getIsPartialPaymentAllowed() { return isPartialPaymentAllowed; }
        public void setIsPartialPaymentAllowed(Boolean isPartialPaymentAllowed) { this.isPartialPaymentAllowed = isPartialPaymentAllowed; }
        public Double getMinimumPartialPaymentPercentage() { return minimumPartialPaymentPercentage; }
        public void setMinimumPartialPaymentPercentage(Double minimumPartialPaymentPercentage) { this.minimumPartialPaymentPercentage = minimumPartialPaymentPercentage; }
        public Double getCodCharge() { return codCharge; }
        public void setCodCharge(Double codCharge) { this.codCharge = codCharge; }
        public Integer getStock() { return stock; }
        public void setStock(Integer stock) { this.stock = stock; }
        public String getSku() { return sku; }
        public void setSku(String sku) { this.sku = sku; }
    }
}
